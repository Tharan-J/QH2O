"use client";

import { useState } from "react";
import { FileText, Download, Calendar, Activity, AlertTriangle, Filter, CheckCircle } from "lucide-react";
import clsx from "clsx";

export default function ReportsPage() {
  const [timeRange, setTimeRange] = useState("7 days");
  const [format, setFormat] = useState("PDF");

  const [device, setDevice] = useState("Main Water Tank");

  const incidentReports = [
    {
      id: "IR-2026-001",
      date: "Mar 12, 2026",
      location: "Main Water Tank",
      incident: "Critical Turbidity Spike",
      status: "Resolved",
      autoGenerated: true
    },
    {
      id: "IR-2026-002",
      date: "Mar 10, 2026",
      location: "Effluent Discharge",
      incident: "TDS Limit Breach",
      status: "Active Investigation",
      autoGenerated: true
    }
  ];

  const handleDownload = () => {
    alert(`Downloading ${timeRange} report for ${device} in ${format} format`);

    const csvRows = ["Time,pH,TDS,Turbidity,ORP"];
    for(let i=0; i<24; i++) {
      const time = `${i.toString().padStart(2, '0')}:00`;
      const ph = (7.0 + (Math.random() * 0.4 - 0.2)).toFixed(1);
      const tds = Math.round(300 + (Math.random() * 30 - 15));
      const turb = (0.8 + (Math.random() * 0.4 - 0.2)).toFixed(1);
      const orp = Math.round(700 + (Math.random() * 40 - 20));
      csvRows.push(`${time},${ph},${tds},${turb},${orp}`);
    }

    const csvContent = csvRows.join("\n");
    const fileContent = format === "PDF" ? "MOCK PDF FILE RECORD\n\n" + csvContent : csvContent;
    const blobArgs = format === "PDF" ? { type: 'application/pdf' } : { type: 'text/csv' };
    
    const blob = new Blob([fileContent], blobArgs);
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${device.replace(/\s+/g, '_')}_Telemetry_${timeRange.replace(/\s+/g, '_')}.${format.toLowerCase()}`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-8 animate-in fade-in duration-500 max-w-5xl mx-auto">
      
      {/* Header */}
      <div className="flex flex-col md:flex-row justify-between items-start md:items-end gap-6 mb-12">
        <div>
          <h1 className="text-4xl font-black tracking-tighter text-slate-900 flex items-center gap-3">
            <FileText className="w-10 h-10 text-sky-500" /> Compliance Reports
          </h1>
          <p className="text-xl text-slate-500 font-medium mt-3">Export verifiable telemtry data for compliance and auditing.</p>
        </div>
      </div>

      <div className="grid grid-cols-1 md:grid-cols-2 gap-8">
        
        {/* Export Configuration Card */}
        <div className="bg-white rounded-[2.5rem] p-8 border border-slate-200 shadow-xl shadow-slate-200/50 flex flex-col min-h-[400px]">
           <div className="flex items-center gap-3 mb-8">
             <Filter className="w-6 h-6 text-slate-400" />
             <h2 className="text-2xl font-black text-slate-900 tracking-tight">Data Export</h2>
           </div>

           <div className="space-y-6 flex-1">
              <div>
                <label className="text-sm font-bold text-slate-500 uppercase tracking-widest block mb-3">Time Range</label>
                <div className="grid grid-cols-3 gap-3">
                  {["24 hours", "7 days", "30 days"].map((range) => (
                    <button 
                      key={range}
                      onClick={() => setTimeRange(range)}
                      className={clsx(
                        "py-3 px-4 rounded-xl font-bold transition-all border",
                        timeRange === range ? "bg-slate-900 text-white border-slate-900 shadow-md" : "bg-slate-50 text-slate-500 border-slate-200 hover:bg-slate-100"
                      )}
                    >
                      {range}
                    </button>
                  ))}
                </div>
              </div>

              <div>
                <label className="text-sm font-bold text-slate-500 uppercase tracking-widest block mb-3">Select Device</label>
                <select 
                  value={device}
                  onChange={(e) => setDevice(e.target.value)}
                  className="w-full bg-slate-50 border border-slate-200 rounded-xl px-4 py-3 font-bold text-slate-900 focus:outline-none focus:ring-2 focus:ring-sky-500/50 appearance-none cursor-pointer"
                >
                  <optgroup label="Industry Nodes">
                    <option>Main Water Tank</option>
                    <option>Medical Centre Monitor</option>
                    <option>Boys Hostel Monitor</option>
                    <option>Girls Hostel Monitor</option>
                    <option>Workshop Outlet</option>
                    <option>Primary Tank Feed</option>
                    <option>Overtank Supply</option>
                  </optgroup>
                  <optgroup label="Village Nodes">
                    <option>Main Village Source</option>
                    <option>Community Tank</option>
                    <option>Primary School Tap</option>
                    <option>Health Centre Outlet</option>
                    <option>Household Drinking Point</option>
                  </optgroup>
                </select>
              </div>

              <div>
                <label className="text-sm font-bold text-slate-500 uppercase tracking-widest block mb-3">Export Format</label>
                <div className="grid grid-cols-2 gap-3">
                  {["PDF", "CSV"].map((fmt) => (
                    <button 
                      key={fmt}
                      onClick={() => setFormat(fmt)}
                      className={clsx(
                        "py-3 px-4 rounded-xl font-bold transition-all border flex items-center justify-center gap-2",
                        format === fmt ? "bg-sky-50 text-sky-700 border-sky-200" : "bg-white text-slate-500 border-slate-200 hover:bg-slate-50"
                      )}
                    >
                      {fmt === "PDF" ? <FileText className="w-4 h-4" /> : <Database className="w-4 h-4" />}
                      {fmt}
                    </button>
                  ))}
                </div>
              </div>
           </div>

           <button 
             onClick={handleDownload}
             className="w-full py-5 mt-8 bg-sky-600 text-white font-black text-lg rounded-2xl shadow-[0_10px_30px_rgba(2,132,199,0.3)] hover:shadow-[0_15px_40px_rgba(2,132,199,0.4)] hover:-translate-y-1 transition-all flex items-center justify-center gap-3"
           >
             Generate Report
             <Download className="w-6 h-6" />
           </button>
        </div>

        {/* Auto-Generated Incident Reports */}
        <div className="bg-slate-900 rounded-[2.5rem] p-8 flex flex-col text-white shadow-[0_20px_50px_rgba(15,23,42,0.3)] relative overflow-hidden min-h-[400px]">
           <div className="absolute top-0 right-0 w-64 h-64 bg-rose-500/10 blur-3xl rounded-full pointer-events-none -mt-20 -mr-20"></div>
           
           <div className="flex items-center gap-3 mb-8 relative z-10">
             <AlertTriangle className="w-6 h-6 text-rose-500" />
             <h2 className="text-2xl font-black tracking-tight text-white">Incident Reports</h2>
           </div>
           
           <p className="text-slate-400 font-medium mb-6 relative z-10">
             Automatically generated when localized water quality breaches WHO thresholds. Designed for immediate environmental health regulatory submission.
           </p>

           <div className="space-y-4 flex-1 relative z-10">
             {incidentReports.map((report) => (
               <div key={report.id} className="bg-slate-800/50 border border-slate-700 rounded-2xl p-5 hover:bg-slate-800 transition-colors group">
                 <div className="flex justify-between items-start mb-3">
                   <div className="bg-rose-500/20 text-rose-300 text-[10px] font-black uppercase tracking-widest px-2.5 py-1 rounded-md">
                     Auto-Generated
                   </div>
                   <span className="text-slate-500 font-bold text-xs flex items-center gap-1">
                     <Calendar className="w-3 h-3" /> {report.date}
                   </span>
                 </div>
                 
                 <h3 className="font-bold text-lg mb-1">{report.incident}</h3>
                 <p className="text-slate-400 text-sm font-medium mb-4">{report.location}</p>

                 <div className="flex justify-between items-center border-t border-slate-700/50 pt-4">
                   <span className={clsx(
                     "text-xs font-bold uppercase tracking-widest flex items-center gap-1.5",
                     report.status === "Resolved" ? "text-emerald-400" : "text-amber-400"
                   )}>
                     {report.status === "Resolved" ? <CheckCircle className="w-4 h-4"/> : <Activity className="w-4 h-4"/>}
                     {report.status}
                   </span>
                   
                   <button className="text-sky-400 font-bold text-sm hover:text-sky-300 transition-colors flex items-center gap-1 group-hover:translate-x-1">
                     Download PDF <Download className="w-4 h-4" />
                   </button>
                 </div>
               </div>
             ))}
           </div>
        </div>

      </div>
    </div>
  );
}

